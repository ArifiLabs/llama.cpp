static bool vk_load_pipelines(moe_cache_vulkan_device & dev) {
    // descriptor set layout: 4 storage buffers + 1 uniform buffer
    VkDescriptorSetLayoutBinding bindings[5] = {};
    for (int i = 0; i < 4; i++) {
        bindings[i].binding = i;
        bindings[i].descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
        bindings[i].descriptorCount = 1;
        bindings[i].stageFlags = VK_SHADER_STAGE_COMPUTE_BIT;
    }
    bindings[4].binding = 4;
    bindings[4].descriptorType = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER;
    bindings[4].descriptorCount = 1;
    bindings[4].stageFlags = VK_SHADER_STAGE_COMPUTE_BIT;

    VkDescriptorSetLayoutCreateInfo dslci = {};
    dslci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
    dslci.bindingCount = 5;
    dslci.pBindings = bindings;
    if (vkCreateDescriptorSetLayout(dev.vk_device, &dslci, nullptr, &dev.ds_layout) != VK_SUCCESS) {
        return false;
    }

    VkPipelineLayoutCreateInfo plci = {};
    plci.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
    plci.setLayoutCount = 1;
    plci.pSetLayouts = &dev.ds_layout;
    if (vkCreatePipelineLayout(dev.vk_device, &plci, nullptr, &dev.pipeline_layout) != VK_SUCCESS) {
        return false;
    }

    VkDescriptorPoolSize pool_sizes[2] = {};
    pool_sizes[0].type = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
    pool_sizes[0].descriptorCount = 4 * 4;
    pool_sizes[1].type = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER;
    pool_sizes[1].descriptorCount = 4;

    VkDescriptorPoolCreateInfo dpci = {};
    dpci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
    dpci.maxSets = 4;
    dpci.poolSizeCount = 2;
    dpci.pPoolSizes = pool_sizes;
    if (vkCreateDescriptorPool(dev.vk_device, &dpci, nullptr, &dev.ds_pool) != VK_SUCCESS) {
        return false;
    }

    VkDescriptorSetAllocateInfo dsai = {};
    dsai.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
    dsai.descriptorPool = dev.ds_pool;
    dsai.descriptorSetCount = 1;
    dsai.pSetLayouts = &dev.ds_layout;
    if (vkAllocateDescriptorSets(dev.vk_device, &dsai, &dev.ds) != VK_SUCCESS) {
        return false;
    }

    if (vk_moe_cache_v2_shader_quant() && dev.host_mapped) {
        // The quant shader reuses ds_layout/pipeline_layout, so it needs only a
        // second descriptor set out of the same pool (maxSets 4).
        dev.pipeline_quant = vk_moe_pipeline_create(
                dev, "moe_cache_quant_q8_1",
                moe_cache_quant_q8_1_data, moe_cache_quant_q8_1_len);
        if (!dev.pipeline_quant ||
            vkAllocateDescriptorSets(dev.vk_device, &dsai, &dev.ds_quant) != VK_SUCCESS) {
            return false;
        }
    }
    return true;
}

// v2 per-device objects: one reusable command buffer and one fence.
static bool vk_v2_create_objects(moe_cache_vulkan_device & dev) {
    VkCommandBufferAllocateInfo ai = {};
    ai.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
    ai.commandPool = dev.vk_cmd_pool;
    ai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
    ai.commandBufferCount = 1;
    if (vkAllocateCommandBuffers(dev.vk_device, &ai, &dev.v2_cmd) != VK_SUCCESS) {
        return false;
    }
    VkFenceCreateInfo fci = {};
    fci.sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO;
    return vkCreateFence(dev.vk_device, &fci, nullptr, &dev.v2_fence) == VK_SUCCESS;
}

// Create the command pool and compile the moe-cache pipelines on first use.
// session_create only keeps bookkeeping state, so a context that never uses
// the cache pays no GPU setup cost.
static bool vk_device_ensure_ready(moe_cache_vulkan_device & dev, size_t budget_mb) {
    std::call_once(dev.init_once, [&]() {
        VkCommandPoolCreateInfo cpci = {};
        cpci.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
        cpci.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
        cpci.queueFamilyIndex = dev.vk_queue_family;
        if (vkCreateCommandPool(dev.vk_device, &cpci, nullptr, &dev.vk_cmd_pool) != VK_SUCCESS) {
            dev.dead.store(true);
            return;
        }
        if (!vk_load_pipelines(dev)) {
            MOE_CACHE_LOG("[moe-cache] Vulkan pipeline creation failed\n");
            dev.free_resources();
            dev.dead.store(true);
            return;
        }
        if (vk_moe_cache_v2() && !vk_v2_create_objects(dev)) {
            MOE_CACHE_LOG("[moe-cache] Vulkan v2 command buffer/fence creation failed\n");
            dev.free_resources();
            dev.dead.store(true);
            return;
        }
        dev.init_ok = true;
        // Probe-visible arm line: which provider actually ran is a receipt, not
        // an inference from the environment the launcher was given.
        MOE_CACHE_LOG("[moe-cache] Vulkan session ready (budget=%zu MiB, %s, arm=%s, act-quant=%s)\n",
                budget_mb, dev.host_mapped ? "host-mapped" : "device-local",
                vk_moe_cache_v2() ? "v2" : "v1",
                vk_moe_cache_v2_shader_quant() && dev.host_mapped && dev.pipeline_quant && dev.ds_quant ? "shader" : "host");
    });
    return dev.init_ok;
}

// ---------------------------------------------------------------------------
// Quantize activations to Q8_1 (scalar, reference quality)
// ---------------------------------------------------------------------------

static void vk_quantize_act_q8_1(const float * src, block_q8_1 * dst,
                                 int64_t n, int64_t padded_n) {
    const int nb = (int)(padded_n / QK8_1);
    for (int ib = 0; ib < nb; ib++) {
        float amax = 0.0f;
        for (int i = 0; i < QK8_1; i++) {
            const int64_t idx = (int64_t)ib * QK8_1 + i;
            const float v = (idx < n) ? src[idx] : 0.0f;
            amax = fmaxf(amax, fabsf(v));
        }
        const float d = amax / 127.0f;
        const float id = (d > 0.0f) ? (1.0f / d) : 0.0f;
        float sum = 0.0f;
        for (int i = 0; i < QK8_1; i++) {
            const int64_t idx = (int64_t)ib * QK8_1 + i;
            const float v = (idx < n) ? src[idx] : 0.0f;
            const int8_t q = (int8_t)roundf(v * id);
            dst[ib].qs[i] = q;
            sum += (float)q * d;
        }
        dst[ib].d = ggml_fp32_to_fp16(d);
        dst[ib].s = ggml_fp32_to_fp16(sum);
    }
}

